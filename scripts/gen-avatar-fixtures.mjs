// Regenerates the avatar model fixtures from the pinned Dither Kit sources.
//
//   node scripts/gen-avatar-fixtures.mjs <path-to-pinned-dither-kit>/registry/dither-kit
//
// Extracts `avatarModel` from avatar.tsx, runs it in Node with the real
// pixel.ts primitives, and writes an ASCII fixture the Rust tests parse.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const upstream = process.argv[2];
if (!upstream) {
  console.error("usage: node scripts/gen-avatar-fixtures.mjs <dither-kit registry dir>");
  process.exit(2);
}

const strip = (src) =>
  src.replace(/^import[\s\S]*?from\s+["'][^"']+["']\s*$/gm, "").replace(/^export\s+/gm, "");

const avatar = readFileSync(join(upstream, "avatar.tsx"), "utf8");
const start = avatar.indexOf("const GRID = 8");
const end = avatar.indexOf("return { on, density, fill: hueFill(hue) }");
if (start < 0 || end < 0) throw new Error("avatarModel not found in avatar.tsx");
const model = avatar.slice(start, avatar.indexOf("\n}\n", end) + 3);

const pixel = strip(readFileSync(join(upstream, "pixel.ts"), "utf8")).replace(
  /^const clamp01 =.*$/m,
  "",
);

const cases = [
  ["ada", "auto"],
  ["Ada Lovelace", "auto"],
  ["🦀", "auto"],
  ["", "auto"],
  ["ada", "horizontal"],
  ["ada", "vertical"],
];

const script = `
${strip(readFileSync(join(upstream, "palette.ts"), "utf8"))}
${pixel}
${model}
const cases = ${JSON.stringify(cases)};
for (const [name, mirror] of cases) {
  const m = avatarModel(name, undefined, mirror);
  console.log(JSON.stringify({ name, mirror, on: m.on, fill: m.fill, density: m.density }));
}
`;

const tmp = join(tmpdir(), `dither-avatars-${process.pid}.ts`);
writeFileSync(tmp, script);
const lines = execFileSync(process.execPath, [tmp], { encoding: "utf8" }).trim().split("\n");

let out = "# generated by scripts/gen-avatar-fixtures.mjs - do not edit\n";
for (const line of lines) {
  const { name, mirror, on, fill, density } = JSON.parse(line);
  out += `[${JSON.stringify(name)}|${mirror}|${fill.join(",")}]\n`;
  for (let r = 0; r < 8; r++) {
    out += on.slice(r * 8, r * 8 + 8).map((v) => (v ? "#" : ".")).join("") + "\n";
  }
  out += `density=${density.map((d) => d.toFixed(4)).join(",")}\n\n`;
}

writeFileSync(join(root, "crates/dither-core/tests/fixtures/avatars.txt"), out);
console.log("wrote avatars.txt");
